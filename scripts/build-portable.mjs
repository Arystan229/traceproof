import { build } from 'esbuild';
import { mkdir, copyFile, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
const target = path.resolve(process.argv[2] || 'outputs/traceproof/portable');
await mkdir(path.join(target, 'public'), { recursive: true });
await build({ entryPoints: ['portable/client.tsx'], outfile: path.join(target, 'public/app.js'), bundle: true, minify: true, platform: 'browser', format: 'esm', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' }, legalComments: 'eof' });
await build({ entryPoints: ['app/api/audit/route.ts'], outfile: path.join(target, 'api.mjs'), bundle: true, platform: 'node', format: 'esm', target: 'node22' });
await build({ entryPoints: ['app/api/config/route.ts'], outfile: path.join(target, 'config.mjs'), bundle: true, platform: 'node', format: 'esm', target: 'node22' });
await copyFile('portable/server.mjs', path.join(target, 'server.mjs'));
await copyFile('portable/index.html', path.join(target, 'public/index.html'));
await copyFile('public/favicon.svg', path.join(target, 'public/favicon.svg'));
await copyFile('LICENSE', path.join(target, 'LICENSE'));
await copyFile('portable/Dockerfile', path.join(target, 'Dockerfile'));
const licenses = await Promise.all(['react', 'react-dom', 'scheduler', 'lucide-react'].map(async name => `${name}\n${await readFile(`node_modules/${name}/LICENSE`, 'utf8')}`));
await writeFile(path.join(target, 'THIRD_PARTY_LICENSES.txt'), licenses.join('\n\n--------------------\n\n'));
const css = (await readFile('app/globals.css', 'utf8')).replace(/^@import[^;]+;\s*/gm, '');
const reset = 'html{line-height:1.5}h1,h2,h3,p,blockquote{margin:0}button,input,textarea,select{font:inherit}button{background:none}dialog{margin:auto}img,svg{vertical-align:middle}';
await writeFile(path.join(target, 'public/app.css'), reset + css);
await writeFile(path.join(target, 'START.cmd'), '@echo off\r\ncd /d "%~dp0"\r\nnode server.mjs\r\npause\r\n');
console.log(`Portable application built: ${target}`);
